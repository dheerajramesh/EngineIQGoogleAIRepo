export function getEngineById(id: string, engines: AircraftEngine[] = INITIAL_FLEET_ENGINES): AircraftEngine | undefined {
  return engines.find((e) => e.id === id);
}

export function getEnginesByTail(tailNumber: string, engines: AircraftEngine[] = INITIAL_FLEET_ENGINES): AircraftEngine[] {
  return engines.filter((e) => e.tailNumber === tailNumber);
}
